@app.route("/api/messages/<int:msg_id>", methods=["DELETE"])
@login_required
def unsend_message(msg_id):
    """Unsend one of your messages, like Claude's edit: the message and everything
    after it (its reply, and any later turns) is removed and any reply still being
    written is stopped. The text and the message's files are handed back so the
    browser can put them in the composer to edit and re-send."""
    with db() as c:
        row = c.execute(
            "SELECT m.conversation_id, m.role, m.content FROM messages m "
            "JOIN conversations cv ON cv.id=m.conversation_id WHERE m.id=? AND cv.user_sub=?",
            (msg_id, current_sub()),
        ).fetchone()
        if not row:
            return jsonify({"error": "Message not found."}), 404
        if row["role"] != "user":
            return jsonify({"error": "Only your own messages can be unsent."}), 400
        conv_id = row["conversation_id"]

        removed = c.execute(
            "SELECT id, status FROM messages WHERE conversation_id=? AND id>=?", (conv_id, msg_id)
        ).fetchall()
        with ACTIVE_LOCK:
            for r in removed:
                if r["status"] == "generating":
                    CANCELLED.add(r["id"])     # generate_reply stops as soon as it sees this

        # The unsent message's files go back to "uploaded, not sent yet" so they can be re-sent.
        kept = [dict(a) for a in c.execute(
            "SELECT id, name, mime, kind, size FROM attachments WHERE message_id=? ORDER BY created_at",
            (msg_id,),
        ).fetchall()]
        c.execute("UPDATE attachments SET message_id=NULL, conversation_id=NULL WHERE message_id=?", (msg_id,))

        later_ids = [r["id"] for r in removed if r["id"] != msg_id]
        if later_ids:
            marks = ",".join("?" * len(later_ids))
            c.execute(f"DELETE FROM attachments WHERE message_id IN ({marks})", later_ids)
        c.execute("DELETE FROM messages WHERE conversation_id=? AND id>=?", (conv_id, msg_id))

        conversation_deleted = not c.execute(
            "SELECT 1 FROM messages WHERE conversation_id=?", (conv_id,)
        ).fetchone()
        if conversation_deleted:
            c.execute("DELETE FROM conversations WHERE id=?", (conv_id,))
        else:
            c.execute("UPDATE conversations SET updated_at=? WHERE id=?", (now(), conv_id))

    return jsonify({"text": row["content"], "attachments": kept, "conversation_deleted": conversation_deleted})


