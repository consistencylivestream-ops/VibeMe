def sniff_image(data):
    """Returns the real image mime type from the file's magic bytes (never
    trusts the browser). SVG is deliberately not allowed — it can carry scripts."""
    if data.startswith(b"\x89PNG\r\n\x1a\n"):
        return "image/png"
    if data.startswith(b"\xff\xd8\xff"):
        return "image/jpeg"
    if data.startswith((b"GIF87a", b"GIF89a")):
        return "image/gif"
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return "image/webp"
    return None


def docx_to_text(data):
    with zipfile.ZipFile(io.BytesIO(data)) as zf:
        info = zf.getinfo("word/document.xml")
        if info.file_size > 30 * 1024 * 1024:
            raise ValueError("Document is too large to read.")
        xml = zf.read("word/document.xml").decode("utf-8", "replace")
    xml = xml.replace("</w:p>", "\n").replace("<w:tab/>", "\t")
    xml = re.sub(r"<w:br[^>]*/>", "\n", xml)
    return html.unescape(re.sub(r"<[^>]+>", "", xml))


def classify_upload(filename, data):
    """Returns (kind, mime, text_content_or_None). Raises ValueError with a
    user-readable message for anything we can't handle."""
    ext = os.path.splitext(filename.lower())[1]

    image_mime = sniff_image(data)
    if image_mime:
        return "image", image_mime, None
    if ext in IMAGE_EXTS:
        raise ValueError("This image is corrupted or not a real PNG/JPEG/WEBP/GIF.")

    if data.startswith(b"%PDF"):
        return "pdf", "application/pdf", None

    if ext == ".docx":
        try:
            text = docx_to_text(data)
        except Exception:
            raise ValueError("Couldn't read this Word file.")
        return "docx", "application/vnd.openxmlformats-officedocument.wordprocessingml.document", text

    if ext in TEXT_EXTS or ext == "":
        if b"\x00" in data[:8192]:
            raise ValueError("This looks like a binary file, not text.")
        return "text", "text/plain", data.decode("utf-8", "replace")

    raise ValueError(
        "Unsupported file type. You can attach images, PDFs, .docx, and text/code files."
    )


def clean_filename(name):
    name = os.path.basename((name or "file").replace("\\", "/"))
    name = re.sub(r"[\x00-\x1f\"<>|]", "", name).strip() or "file"
    return name[:120]


@app.route("/api/upload", methods=["POST"])
@login_required
def upload():
    files = request.files.getlist("files")
    if not files:
        return jsonify({"error": "No file received."}), 400

    sub = current_sub()
    saved, errors = [], []
    for f in files:
        name = clean_filename(f.filename)
        data = f.read()
        if not data:
            errors.append({"name": name, "error": "The file is empty."})
            continue
        if len(data) > MAX_FILE_BYTES:
            errors.append({"name": name, "error": "File is too large (max 20 MB)."})
            continue
        try:
            kind, mime, text = classify_upload(name, data)
        except ValueError as exc:
            errors.append({"name": name, "error": str(exc)})
            continue

        att_id = uuid.uuid4().hex
        with db() as c:
            c.execute(
                "INSERT INTO attachments (id, user_sub, name, mime, kind, size, data, text_content, created_at)"
                " VALUES (?,?,?,?,?,?,?,?,?)",
                (att_id, sub, name, mime, kind, len(data), data, text, time.time()),
            )
        saved.append({"id": att_id, "name": name, "mime": mime, "kind": kind, "size": len(data)})

    status = 200 if saved or not errors else 400
    return jsonify({"attachments": saved, "errors": errors}), status


