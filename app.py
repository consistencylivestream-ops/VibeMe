def build_history(conn, conv_id, before_msg_id):
    """Rebuilds the OpenAI message list for a conversation from the database.
    To keep token use low it (a) only includes the last MAX_HISTORY_MESSAGES
    messages and (b) only re-sends the files of the MOST RECENT message that had
    attachments; older attachments are replaced by a one-line note."""
    rows = conn.execute(
        "SELECT id, role, content, status FROM messages WHERE conversation_id=? AND id<? ORDER BY id DESC LIMIT ?",
        (conv_id, before_msg_id, MAX_HISTORY_MESSAGES),
    ).fetchall()
    rows = list(reversed(rows))
    if rows and rows[0]["role"] == "assistant":
        rows = rows[1:]             # don't start the window with an orphan reply

    latest_att = conn.execute(
        "SELECT MAX(message_id) FROM attachments WHERE conversation_id=? AND message_id<?",
        (conv_id, before_msg_id),
    ).fetchone()[0]

    history = []
    for m in rows:
        if m["role"] == "assistant":
            if m["status"] == "done" and m["content"].strip():
                history.append({"role": "assistant", "content": m["content"]})
            continue

        atts = conn.execute(
            "SELECT name, mime, kind, data, text_content FROM attachments WHERE message_id=? ORDER BY created_at",
            (m["id"],),
        ).fetchall()
        if not atts:
            history.append({"role": "user", "content": m["content"]})
            continue

        if m["id"] != latest_att:
            names = ", ".join(a["name"] for a in atts)
            note = f"[Earlier attachment(s): {names} - not re-sent to save tokens; ask the user to re-attach if you need them again.]"
            history.append({"role": "user", "content": (note + "\n" + m["content"]).strip()})
            continue

        parts = []
        for a in atts:
            if a["kind"] in ("text", "docx"):
                text = a["text_content"] or ""
                note = ""
                if len(text) > MAX_TEXT_CHARS:
                    text = text[:MAX_TEXT_CHARS]
                    note = "\n[File truncated — it was too long to include in full.]"
                parts.append({"type": "text", "text": f'<file name="{a["name"]}">\n{text}{note}\n</file>'})
            elif a["kind"] == "image":
                b64 = base64.b64encode(a["data"]).decode("ascii")
                parts.append({"type": "image_url", "image_url": {"url": f'data:{a["mime"]};base64,{b64}'}})
            elif a["kind"] == "pdf":
                b64 = base64.b64encode(a["data"]).decode("ascii")
                parts.append({"type": "file", "file": {
                    "filename": a["name"],
                    "file_data": f"data:application/pdf;base64,{b64}",
                }})
        if m["content"].strip():
            parts.append({"type": "text", "text": m["content"]})
        history.append({"role": "user", "content": parts})
    return history


def generate_reply(msg_id, conv_id, client, model, temperature, max_tokens):
    """Runs in a background thread. Writes the growing reply into the database
    so it survives the browser going away; any page can (re)attach to it."""
    with ACTIVE_LOCK:
        ACTIVE_JOBS.add(msg_id)

    text = ""
    status = "done"
    last_flush = 0.0
    try:
        with db() as conn:
            messages = [{"role": "system", "content": SYSTEM_PROMPT}] + build_history(conn, conv_id, msg_id)

        if msg_id in CANCELLED:     # unsent before the request even started
            return
        kwargs = dict(model=model, messages=messages, stream=True, max_completion_tokens=max_tokens)
        if model in SEARCH_MODELS:
            # Search models browse the web natively and don't accept a temperature override.
            kwargs["web_search_options"] = {}
        else:
            kwargs["temperature"] = temperature

        stream = client.chat.completions.create(**kwargs)
        finish = None
        for chunk in stream:
            if msg_id in CANCELLED:     # the message was unsent: stop paying for tokens
                try:
                    stream.close()
                except Exception:
                    pass
                break
            if not chunk.choices:
                continue
            choice = chunk.choices[0]
            if choice.finish_reason:
                finish = choice.finish_reason
            delta = choice.delta
            if delta and delta.content:
                text += delta.content
                t = time.time()
                if t - last_flush >= 0.2:
                    with db() as conn:
                        conn.execute(
                            "UPDATE messages SET content=?, updated_at=? WHERE id=?",
                            (text, t, msg_id),
                        )
                    last_flush = t
        if finish == "length":
            text += '\n\n*(Reply hit the length limit to save tokens - say "continue" and I will pick up from here.)*'
    except Exception as exc:  # surface the error into the saved reply
        text += f"\n\n**Error:** {exc}"
        status = "error"
    finally:
        try:
            if not text.strip():
                text = "*(The model returned an empty reply. Try rephrasing.)*"
            with db() as conn:
                conn.execute(
                    "UPDATE messages SET content=?, status=?, updated_at=? WHERE id=?",
                    (text, status, time.time(), msg_id),
                )
                conn.execute("UPDATE conversations SET updated_at=? WHERE id=?", (time.time(), conv_id))
        finally:
            with ACTIVE_LOCK:
                ACTIVE_JOBS.discard(msg_id)
                CANCELLED.discard(msg_id)


@app.route("/api/chat", methods=["POST"])
@login_required
def chat():
    """Saves the user's message (with any attachments), creates the assistant's
    placeholder reply, starts generating it in the background, and returns
    immediately. The browser then streams it from /api/messages/<id>/stream.

    The browser may send its own API key / temperature per request. A non-default
    model is honoured when a personal API key is sent or with a valid `access_code`;
    otherwise the default (cheapest) model is used and a `notice` is returned.
    """
    data = request.get_json(force=True)
    text = (data.get("text") or "").strip()
    attachment_ids = data.get("attachment_ids") or []
    conv_id = data.get("conversation_id") or None

    if not isinstance(attachment_ids, list) or len(attachment_ids) > MAX_ATTACHMENTS_PER_MESSAGE:
        return jsonify({"error": f"You can attach up to {MAX_ATTACHMENTS_PER_MESSAGE} files per message."}), 400
    if not text and not attachment_ids:
        return jsonify({"error": "Type a message or attach a file."}), 400
    if len(text) > 100_000:
        return jsonify({"error": "That message is too long."}), 400

    user_key = (data.get("api_key") or "").strip()
    sub = current_sub()

    # Everyone gets the cheap default model. Another model is used when the person
    # brings their OWN OpenAI key (they pay, so no limits) or the request carries the
    # current, unexpired access code (see /api/model-access).
    requested = data.get("model") or DEFAULT_MODEL
    model, notice = DEFAULT_MODEL, None
    if requested != DEFAULT_MODEL and requested in ALLOWED_MODELS:
        if user_key or access_code_valid(data.get("access_code")):
            model = requested
        else:
            notice = f"Access code missing or expired - using {DEFAULT_MODEL}. Get a new code in Settings."
    max_tokens = MAX_OUTPUT_TOKENS_UNLOCKED if (user_key or model != DEFAULT_MODEL) else MAX_OUTPUT_TOKENS
    temperature = data.get("temperature")
    temperature = 0.4 if temperature is None else max(0.0, min(1.0, float(temperature)))

    active_client = OpenAI(api_key=user_key) if user_key else server_client
    if active_client is None:
        return jsonify({"error": "No OpenAI API key configured. Add one in Settings, or set OPENAI_API_KEY on the server."}), 500

    t = now()
    with db() as c:
        if conv_id:
            conv = c.execute("SELECT id FROM conversations WHERE id=? AND user_sub=?", (conv_id, sub)).fetchone()
            if not conv:
                return jsonify({"error": "Conversation not found."}), 404
            expire_stale(c, conv_id)
            if c.execute("SELECT 1 FROM messages WHERE conversation_id=? AND status='generating'", (conv_id,)).fetchone():
                return jsonify({"error": "VibeMe is still replying in this chat. Wait for it to finish."}), 409
        else:
            conv_id = uuid.uuid4().hex

        # Only files this user uploaded and hasn't already sent.
        atts = []
        if attachment_ids:
            marks = ",".join("?" * len(attachment_ids))
            atts = c.execute(
                f"SELECT id, name FROM attachments WHERE id IN ({marks}) AND user_sub=? AND message_id IS NULL",
                (*attachment_ids, sub),
            ).fetchall()
            if len(atts) != len(set(attachment_ids)):
                return jsonify({"error": "One of the attached files is no longer available. Please attach it again."}), 400

        is_new = not c.execute("SELECT 1 FROM conversations WHERE id=?", (conv_id,)).fetchone()
        if is_new:
            base = " ".join(text.split()) or (atts[0]["name"] if atts else "New chat")
            title = base[:48] + ("…" if len(base) > 48 else "")
            c.execute(
                "INSERT INTO conversations (id, user_sub, title, created_at, updated_at) VALUES (?,?,?,?,?)",
                (conv_id, sub, title, t, t),
            )
        else:
            c.execute("UPDATE conversations SET updated_at=? WHERE id=?", (t, conv_id))

        cur = c.execute(
            "INSERT INTO messages (conversation_id, role, content, status, created_at, updated_at)"
            " VALUES (?,?,?,?,?,?)",
            (conv_id, "user", text, "done", t, t),
        )
        user_msg_id = cur.lastrowid
        for a in atts:
            c.execute(
                "UPDATE attachments SET message_id=?, conversation_id=? WHERE id=?",
                (user_msg_id, conv_id, a["id"]),
            )
        cur = c.execute(
            "INSERT INTO messages (conversation_id, role, content, status, created_at, updated_at)"
            " VALUES (?,?,?,?,?,?)",
            (conv_id, "assistant", "", "generating", t, t),
        )
        assistant_msg_id = cur.lastrowid
        user_msg = serialize_message(c, {"id": user_msg_id, "role": "user", "content": text, "status": "done"})

    threading.Thread(
        target=generate_reply,
        args=(assistant_msg_id, conv_id, active_client, model, temperature, max_tokens),
        daemon=True,
    ).start()

    return jsonify({
        "conversation_id": conv_id,
        "user_message": user_msg,
        "assistant_message_id": assistant_msg_id,
        "model_used": model,
        "notice": notice,
    })


@app.route("/api/model-access", methods=["POST"])
@login_required
def model_access():
    """Trade the secret key for the current access code (shared by everyone; lives
    CODE_TTL_SECONDS). The browser attaches the code to each question."""
    data = request.get_json(force=True)
    key = (data.get("key") or "").strip()
    sub = current_sub()
    t = time.time()

    with ACCESS_LOCK:
        fails = [x for x in KEY_FAILS.get(sub, []) if t - x < 600]
        KEY_FAILS[sub] = fails
        if len(fails) >= 5:
            return jsonify({"error": "Too many wrong keys. Try again in 10 minutes."}), 429

    if not MASTER_KEY or not _same(key, MASTER_KEY):
        with ACCESS_LOCK:
            KEY_FAILS.setdefault(sub, []).append(t)
        return jsonify({"error": "Wrong secret key."}), 403

    with ACCESS_LOCK:
        KEY_FAILS.pop(sub, None)
    code, left = current_access_code()
    return jsonify({"code": code, "expires_in": left})


@app.route("/api/messages/<int:msg_id>/stream")
@login_required
def stream_message(msg_id):
    """Server-Sent Events tail of a reply. `offset` is how many characters the
    page already has, so a page that left and came back only receives the rest.
    Closing this connection does NOT stop the reply — it keeps being written."""
    try:
        offset = max(0, int(request.args.get("offset", 0)))
    except ValueError:
        offset = 0

    with db() as c:
        owned = c.execute(
            "SELECT m.conversation_id FROM messages m JOIN conversations cv ON cv.id=m.conversation_id "
            "WHERE m.id=? AND cv.user_sub=?",
            (msg_id, current_sub()),
        ).fetchone()
    if not owned:
        return jsonify({"error": "Not found."}), 404
    conv_id = owned["conversation_id"]

    def generate():
        sent = offset
        deadline = time.time() + STREAM_MAX_SECONDS
        last_ping = time.time()
        while time.time() < deadline:
            with db() as conn:
                expire_stale(conn, conv_id)
                m = conn.execute("SELECT content, status FROM messages WHERE id=?", (msg_id,)).fetchone()
            if m is None:  # conversation was deleted while streaming
                yield f"data: {json.dumps({'done': True})}\n\n"
                return

            content = m["content"]
            if len(content) > sent:
                yield f"data: {json.dumps({'token': content[sent:]})}\n\n"
                sent = len(content)
                last_ping = time.time()

            if m["status"] != "generating":
                yield f"data: {json.dumps({'done': True, 'status': m['status']})}\n\n"
                return

            if time.time() - last_ping > 15:
                yield ": ping\n\n"  # keeps proxies from closing an idle connection
                last_ping = time.time()
            time.sleep(0.15)

    return Response(
        generate(),
        mimetype="text/event-stream",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
    )


@app.route("/api/zip", methods=["POST"])
@login_required
def make_zip():
    """
    Takes {"project_name": "...", "files": [{"path": "...", "content": "..."}]}
    and returns a downloadable .zip built in memory.
    """
    data = request.get_json(force=True)
    project_name = data.get("project_name") or "vibeme-project"
    files = data.get("files", [])

    if not files:
        return jsonify({"error": "No files to package."}), 400

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        for f in files:
            path = f.get("path", "file.txt").lstrip("/")
            content = f.get("content", "")
            zf.writestr(path, content)
    buffer.seek(0)

    return send_file(
        buffer,
        mimetype="application/zip",
        as_attachment=True,
        download_name=f"{project_name}.zip",
    )


