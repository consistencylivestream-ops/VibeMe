ACCESS_LOCK = threading.Lock()
_CODE_ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"   # no 0/O/1/I so codes are easy to copy


def _same(a, b):
    return hmac.compare_digest(a.encode("utf-8"), b.encode("utf-8"))


def current_access_code():
    """Returns (code, seconds_left). Makes a new code only if the old one expired."""
    with ACCESS_LOCK:
        t = time.time()
        if not ACCESS_CODE["code"] or ACCESS_CODE["expires"] <= t:
            raw = "".join(secrets.choice(_CODE_ALPHABET) for _ in range(8))
            ACCESS_CODE["code"] = raw[:4] + "-" + raw[4:]
            ACCESS_CODE["expires"] = t + CODE_TTL_SECONDS
        return ACCESS_CODE["code"], max(1, int(ACCESS_CODE["expires"] - t))


def access_code_valid(code):
    code = (code or "").strip().upper()
    with ACCESS_LOCK:
        live = ACCESS_CODE["code"] if ACCESS_CODE["expires"] > time.time() else None
    return bool(code) and bool(live) and _same(live, code)


