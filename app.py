def now():
    return time.time()


def expire_stale(conn, conv_id):
    """If a reply is stuck in 'generating' with no worker alive (server was
    restarted mid-answer), mark it as interrupted so the UI stops waiting."""
    cutoff = now() - STALE_AFTER_SECONDS
    rows = conn.execute(
        "SELECT id FROM messages WHERE conversation_id=? AND status='generating' AND updated_at<?",
        (conv_id, cutoff),
    ).fetchall()
    for r in rows:
        with ACTIVE_LOCK:
            alive = r["id"] in ACTIVE_JOBS
        if alive:
            continue
        conn.execute(
            "UPDATE messages SET status='error', content=content || ?, updated_at=? WHERE id=?",
            ("\n\n**Error:** This reply was interrupted because the server restarted. Please send your message again.", now(), r["id"]),
        )


def serialize_message(conn, m):
    atts = conn.execute(
        "SELECT id, name, mime, kind, size FROM attachments WHERE message_id=? ORDER BY created_at",
        (m["id"],),
    ).fetchall()
    return {
        "id": m["id"],
        "role": m["role"],
        "content": m["content"],
        "status": m["status"],
        "attachments": [dict(a) for a in atts],
    }


