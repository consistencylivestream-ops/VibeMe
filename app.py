@app.route("/api/auth/google", methods=["POST"])
def auth_google():
    """Verifies the Google ID token from the Sign in with Google button and
    starts a long-lived session. Works identically for a brand-new account
    (signup) and a returning one (login) — Google tells us which via the
    token, but we don't need to care: we just upsert the session user."""
    if not GOOGLE_CLIENT_ID:
        return jsonify({"error": "Server has no GOOGLE_CLIENT_ID configured. See README."}), 500

    data = request.get_json(force=True)
    credential = data.get("credential", "")
    try:
        info = google_id_token.verify_oauth2_token(
            credential, google_requests.Request(), GOOGLE_CLIENT_ID
        )
    except Exception as exc:
        return jsonify({"error": f"Google sign-in failed: {exc}"}), 401

    session["user"] = {
        "sub": info.get("sub"),
        "email": info.get("email"),
        "name": info.get("name") or info.get("email"),
        "picture": info.get("picture"),
    }
    return jsonify({"user": session["user"]})


