@contextmanager
def db():
    conn = sqlite3.connect(DB_PATH, timeout=30)
    conn.row_factory = sqlite3.Row
    try:
        yield conn
        conn.commit()
    finally:
        conn.close()


def init_db():
    with db() as c:
        c.execute("PRAGMA journal_mode=WAL")
        c.executescript(
            """
            CREATE TABLE IF NOT EXISTS conversations (
                id          TEXT PRIMARY KEY,
                user_sub    TEXT NOT NULL,
                title       TEXT NOT NULL DEFAULT '',
                created_at  REAL NOT NULL,
                updated_at  REAL NOT NULL
            );
            CREATE INDEX IF NOT EXISTS idx_conv_user ON conversations(user_sub, updated_at DESC);

            CREATE TABLE IF NOT EXISTS messages (
                id              INTEGER PRIMARY KEY AUTOINCREMENT,
                conversation_id TEXT NOT NULL,
                role            TEXT NOT NULL,
                content         TEXT NOT NULL DEFAULT '',
                status          TEXT NOT NULL DEFAULT 'done',   -- done | generating | error
                created_at      REAL NOT NULL,
                updated_at      REAL NOT NULL
            );
            CREATE INDEX IF NOT EXISTS idx_msg_conv ON messages(conversation_id, id);

            CREATE TABLE IF NOT EXISTS attachments (
                id              TEXT PRIMARY KEY,
                user_sub        TEXT NOT NULL,
                conversation_id TEXT,
                message_id      INTEGER,
                name            TEXT NOT NULL,
                mime            TEXT NOT NULL,
                kind            TEXT NOT NULL,                  -- image | pdf | text | docx
                size            INTEGER NOT NULL,
                data            BLOB NOT NULL,
                text_content    TEXT,
                created_at      REAL NOT NULL
            );
            CREATE INDEX IF NOT EXISTS idx_att_msg ON attachments(message_id);
            """
        )
        # Files that were uploaded but never sent with a message: clean up after a day.
        c.execute(
            "DELETE FROM attachments WHERE message_id IS NULL AND created_at < ?",
            (time.time() - 86400,),
        )


