@app.route("/api/import", methods=["POST"])
@login_required
def import_local_history():
    """One-time migration of chats that older versions kept in the browser's
    localStorage. Text only (old chats had no attachments)."""
    data = request.get_json(force=True)
    items = (data.get("conversations") or [])[:200]
    sub = current_sub()
    id_map = {}
    with db() as c:
        for old in items:
            msgs = [
                m for m in (old.get("messages") or [])[:2000]
                if m.get("role") in ("user", "assistant") and isinstance(m.get("content"), str)
            ]
            if not msgs:
                continue
            new_id = uuid.uuid4().hex
            updated = float(old.get("updatedAt") or now() * 1000) / 1000.0
            title = str(old.get("title") or "Imported chat")[:80]
            c.execute(
                "INSERT INTO conversations (id, user_sub, title, created_at, updated_at) VALUES (?,?,?,?,?)",
                (new_id, sub, title, updated, updated),
            )
            for m in msgs:
                c.execute(
                    "INSERT INTO messages (conversation_id, role, content, status, created_at, updated_at)"
                    " VALUES (?,?,?,?,?,?)",
                    (new_id, m["role"], m["content"], "done", updated, updated),
                )
            id_map[str(old.get("id"))] = new_id
    return jsonify({"id_map": id_map})


